using System.Numerics;
using Content.Client.Resources;
using Content.Client.UserInterface.Controls;
using Content.Shared._ROBUST.Match.Retakes.RobustLoadouts;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._ROBUST.Match.RobustLoadouts;

[GenerateTypedNameReferences]
public sealed partial class RobustLoadoutSelectionWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private IEntityManager _ent = default!;
    [Dependency] private IResourceCache _cache = default!;

    private readonly SpriteSystem _sprite;

    private List<ProtoId<RobustKitPrototype>> Kits;

    public event Action<int>? OnKitChosen;

    public RobustLoadoutSelectionWindow(List<ProtoId<RobustKitPrototype>> kits)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _sprite = _ent.System<SpriteSystem>();

        // Save the proto so we can use it later.
        Kits = kits;

        for (var i=0; i < Kits.Count; i++)
        {
            var kit = Kits[i];
            CreateKit(kit, i);
        }
    }

    private void CreateKit(ProtoId<RobustKitPrototype> kit, int kitNumber)
    {
        var kitProto = _proto.Index(kit);

        var container = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(10,10,10,10),
            HorizontalAlignment = HAlignment.Center,
        };

        var name = new Label
        {
            Text = kitProto.Name,
            Margin = new Thickness(5),
        };

        var description = new Label
        {
            Text = kitProto.Description,
            Margin = new Thickness(5),
        };

        var button = new Button
        {
            Text = "Select Kit!",
            Margin = new Thickness(0,10,0,10),
        };

        button.OnPressed += _ => OnKitChosen?.Invoke(kitNumber);

        container.AddChild(name);
        container.AddChild(description);
        container.AddChild(button);

        MainContainer.AddChild(container);
    }
}
